def t(lang: str, key: str, **kw) -> str:
    """Look up a UI string; fall back to English, then the key itself."""
    table = STRINGS.get(lang, STRINGS["en"])
    s = table.get(key) or STRINGS["en"].get(key, key)
    return s.format(**kw) if kw else s
